"""
compiler/operators/gpl_operators.py
=====================================
GPL operator library — the computation engine for Branch A compilation.

Each operator is a pure function:
  - Takes declarative arguments (atom canonical_id, agg type, column, filters, etc.)
  - Reads data only from the CSV root set by build_namespace()
  - Returns a dict with at minimum: {oracle_value, formula_line}
  - Never modifies any file or global state

OPERATORS IN THIS FILE:
  MEASURE                   — simple aggregation, no time window, no dedup
  MEASURE_SNAPSHOT_DEDUPED  — state-table dedup (dedup THEN filter)
  MEASURE_MONTH_FIXED       — this_month / last_month
  MEASURE_QUARTER_FIXED     — this_quarter / last_quarter / this_year / last_year
  MEASURE_YTD               — year to date (Jan 1 → today)
  MEASURE_GROUPED           — grouped by dimension or time bucket
                              supports in-memory FK join for cross-table goals

ADDING NEW OPERATORS:
  New operators should be added in this file following the same pattern:
    1. Decorate with @gpl_operator
    2. Implement computation only — do NOT build formula strings manually
    3. Return {"oracle_value": value, ...} — formula_line is injected automatically
    4. Register the new function in build_namespace() below

  The @gpl_operator decorator auto-generates an executable formula_line from the
  actual arguments the operator was called with. New operators get this for free.

EXECUTION MODEL:
  Branch A builds a formula_line string by calling the operator via @gpl_operator.
  The compiler exec()s that string against a namespace built by build_namespace().
  The operator runs, and the oracle_value is extracted from the namespace.

  formula_line IS the executable artifact — it gets stored in the aterm and
  shipped to the customer runtime, where it executes against real data using
  the same operator functions registered in build_namespace().
"""

