def _entity_set(rows: List[Dict], entity_col: str, date_col: str,
                start: str, end: str) -> set:
    """Return set of entity_col values active within [start, end]."""
    result = set()
    for r in rows:
        d = str(r.get(date_col, ""))
        if start <= d <= end:
            result.add(str(r.get(entity_col, "")))
    return result


