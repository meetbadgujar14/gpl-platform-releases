@gpl_operator
def MEASURE_LINEAR_TREND(
    atom_canonical_id: str,
    date_col: str,
    column: str,
    agg: str = "SUM",
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Linear regression slope over monthly aggregated data.
    Returns slope (positive = upward trend, negative = downward).
    """
    import pandas as pd

    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    if not filtered:
        return {"oracle_value": 0.0, "row_count": 0}

    df = pd.DataFrame(filtered)
    df[date_col] = pd.to_datetime(df[date_col], errors="coerce")
    df[column]   = pd.to_numeric(df[column], errors="coerce").fillna(0)
    df["_period"] = df[date_col].dt.to_period("M")

    agg_fn  = "sum" if agg.upper() == "SUM" else "mean"
    monthly = df.groupby("_period")[column].agg(agg_fn).sort_index()

    if len(monthly) < 2:
        return {"oracle_value": 0.0, "row_count": len(filtered)}

    x     = np.arange(len(monthly), dtype=float)
    y     = monthly.values.astype(float)
    slope = float(np.polyfit(x, y, 1)[0])

    return {"oracle_value": slope, "row_count": len(filtered), "periods_used": len(monthly)}


# ── WINDOW RANK OPERATOR ──────────────────────────────────────────────────────

@gpl_operator
def MEASURE_WINDOW_RANK(
    atom_canonical_id: str,
    rank_col: str,
    entity_col: str,
    entity_value: str,
    agg: str = "SUM",
    filters: Optional[List[Dict]] = None,
    ascending: bool = False,
) -> Dict:
    """
    Rank of a specific entity within its partition.
    Returns rank as float (1.0 = best).
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)

    groups: Dict[str, float] = {}
    for r in filtered:
        key = str(r.get(entity_col, ""))
        try:
            groups[key] = groups.get(key, 0.0) + float(r.get(rank_col, 0) or 0)
        except (TypeError, ValueError):
            pass

    sorted_entities = sorted(groups.items(), key=lambda x: x[1], reverse=not ascending)
    rank = next((i + 1 for i, (k, _) in enumerate(sorted_entities) if k == str(entity_value)), 0)

    return {
        "oracle_value":    float(rank),
        "total_entities":  len(groups),
        "entity_value":    entity_value,
    }


# ── CONCENTRATION OPERATORS ───────────────────────────────────────────────────

def _entity_totals(rows: List[Dict], entity_col: str, measure_col: str) -> List[float]:
    """Aggregate measure_col by entity_col, return sorted list of totals."""
    totals: Dict[str, float] = {}
    for r in rows:
        key = str(r.get(entity_col, ""))
        try:
            totals[key] = totals.get(key, 0.0) + float(r.get(measure_col, 0) or 0)
        except (TypeError, ValueError):
            pass
    return sorted(totals.values())


@gpl_operator
def MEASURE_PARETO_RATIO(
    atom_canonical_id: str,
    entity_col: str,
    measure_col: str,
    top_pct: float = 20.0,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """% of total measure contributed by the top top_pct% of entities."""
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    totals   = _entity_totals(filtered, entity_col, measure_col)

    if not totals or sum(totals) == 0:
        return {"oracle_value": 0.0, "row_count": len(filtered)}

    n_top      = max(1, int(len(totals) * top_pct / 100))
    top_sum    = sum(sorted(totals, reverse=True)[:n_top])
    value      = float(top_sum / sum(totals) * 100)

    return {"oracle_value": value, "row_count": len(filtered), "top_pct": top_pct}


@gpl_operator
def MEASURE_HERFINDAHL(
    atom_canonical_id: str,
    entity_col: str,
    measure_col: str,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """Herfindahl-Hirschman Index: sum of squared market shares (0–1 scale)."""
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    totals   = _entity_totals(filtered, entity_col, measure_col)
    grand    = sum(totals)

    if not totals or grand == 0:
        return {"oracle_value": 0.0, "row_count": len(filtered)}

    shares = [t / grand for t in totals]
    value  = float(sum(s ** 2 for s in shares))

    return {"oracle_value": value, "row_count": len(filtered)}


@gpl_operator
def MEASURE_GINI(
    atom_canonical_id: str,
    entity_col: str,
    measure_col: str,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """Gini coefficient of inequality (0 = perfect equality, 1 = max inequality)."""
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    totals   = _entity_totals(filtered, entity_col, measure_col)

    if len(totals) < 2 or sum(totals) == 0:
        return {"oracle_value": 0.0, "row_count": len(filtered)}

    a     = np.array(sorted(totals), dtype=float)
    n     = len(a)
    value = float((2 * np.sum(np.arange(1, n + 1) * a) / (n * np.sum(a))) - (n + 1) / n)

    return {"oracle_value": max(0.0, value), "row_count": len(filtered)}


