@gpl_operator
def MEASURE_COHORT_RETENTION(
    atom_canonical_id: str,
    entity_col: str,
    date_col: str,
    cohort_start: str,
    cohort_end: str,
    retention_days: int,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    % of entities from the cohort window still active after retention_days.
    Returns a percentage float (0–100).
    """
    from datetime import datetime, timedelta

    rows   = apply_filters(load_csv(atom_canonical_id), filters)
    cohort = _entity_set(rows, entity_col, date_col, cohort_start, cohort_end)

    if not cohort:
        return {"oracle_value": 0.0, "cohort_size": 0, "row_count": len(rows)}

    try:
        ret_start = cohort_end
        ret_end   = (datetime.strptime(cohort_end, "%Y-%m-%d") +
                     timedelta(days=retention_days)).strftime("%Y-%m-%d")
    except ValueError:
        return {"oracle_value": 0.0, "cohort_size": len(cohort), "row_count": len(rows)}

    retained = _entity_set(rows, entity_col, date_col, ret_start, ret_end)
    value    = float(len(cohort & retained) / len(cohort) * 100)

    return {
        "oracle_value":    value,
        "cohort_size":     len(cohort),
        "retained_count":  len(cohort & retained),
        "row_count":       len(rows),
    }


# ── CORRELATION OPERATOR ──────────────────────────────────────────────────────

@gpl_operator
def MEASURE_CORRELATION(
    atom_canonical_id: str,
    col_a: str,
    col_b: str,
    method: str = "pearson",
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Pearson or Spearman correlation between two columns in the same table.
    Returns coefficient in [-1.0, 1.0].
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)

    pairs = []
    for r in filtered:
        try:
            a = float(r.get(col_a, None))
            b = float(r.get(col_b, None))
            pairs.append((a, b))
        except (TypeError, ValueError):
            pass

    if len(pairs) < 2:
        return {"oracle_value": 0.0, "row_count": len(filtered)}

    a_arr = np.array([p[0] for p in pairs])
    b_arr = np.array([p[1] for p in pairs])

    if method == "spearman":
        from scipy.stats import spearmanr
        coeff, _ = spearmanr(a_arr, b_arr)
    else:
        coeff = float(np.corrcoef(a_arr, b_arr)[0, 1])

    return {"oracle_value": float(coeff), "row_count": len(filtered), "method": method}


