# ── MEASURE_GROUPED ───────────────────────────────────────────────────────────

@gpl_operator
def MEASURE_GROUPED(
    atom_canonical_id: str,
    agg: str,
    column: Optional[str],
    group_by_col: Optional[str] = None,
    filters: Optional[List[Dict]] = None,
    join_atom_canonical_id: Optional[str] = None,
    join_from_field: Optional[str] = None,
    join_to_field: Optional[str] = None,
    time_bucket: Optional[Dict] = None,
) -> Dict:
    """
    Aggregation grouped by a dimension or time bucket.

    Covers two goal types:
      1. Series goals (Wave 8): group by a calendar bucket derived from a
         date column — pass time_bucket={"date_col": ..., "granularity": "month"}
         instead of group_by_col.

      2. Cross-table goals (Wave 7): group by a column on a JOINED atom —
         pass join_atom_canonical_id + join_from_field + join_to_field.
         The join is an in-memory left-inner join: rows with no FK match
         are excluded (same behaviour as SQL INNER JOIN).

    Args:
        atom_canonical_id:      primary atom to read
        agg:                    aggregation type
        column:                 column to aggregate (on primary atom)
        group_by_col:           column name to group by (may be on joined atom)
        filters:                applied after join and before grouping
        join_atom_canonical_id: secondary atom for FK join (optional)
        join_from_field:        FK column on primary atom (e.g. "customer_id")
        join_to_field:          PK column on secondary atom (e.g. "id")
        time_bucket:            {"date_col": str, "granularity": "month"|"quarter"|...}
                                if set, overrides group_by_col

    Returns:
        {
            oracle_value: dict {group_key: float},   ← breakdown by group
            row_count:    int,
            group_count:  int,
            formula_line: str,
        }
    Note: oracle_value is a DICT for grouped goals, not a single float.
    The aterm stores this as-is; the runtime renders it as a table/chart.
    """
    rows = load_csv(atom_canonical_id)

    # ── In-memory FK join ───────────────────────────────────────────────────
    if join_atom_canonical_id and join_from_field and join_to_field:
        join_rows   = load_csv(join_atom_canonical_id)
        join_lookup = {str(r.get(join_to_field, "")).strip(): r
                       for r in join_rows}

        joined = []
        for r in rows:
            fk_val = str(r.get(join_from_field, "")).strip()
            match  = join_lookup.get(fk_val)
            if match:
                merged = dict(r)
                # Bring joined columns across, without overwriting primary cols
                for k, v in match.items():
                    merged.setdefault(k, v)
                joined.append(merged)

        if not joined:
            log.warning(
                f"[MEASURE_GROUPED] Join produced 0 rows: "
                f"{atom_canonical_id}.{join_from_field} → "
                f"{join_atom_canonical_id}.{join_to_field}"
            )
        rows = joined

    filtered = apply_filters(rows, filters)

    # ── Group and aggregate ─────────────────────────────────────────────────
    groups: Dict[str, List[Dict]] = {}
    for r in filtered:
        if time_bucket:
            key = bucket_date_key(
                r.get(time_bucket["date_col"]),
                time_bucket["granularity"],
            )
        else:
            key = r.get(group_by_col)
        if key is None:
            continue
        groups.setdefault(str(key), []).append(r)

    result = {
        group_key: aggregate(group_rows, agg, column)
        for group_key, group_rows in sorted(groups.items())
    }

    return {
        "oracle_value": result,
        "row_count":    len(filtered),
        "group_count":  len(result),
    }


# ── MEASURE_GROUPED_YTD ───────────────────────────────────────────────────────

@gpl_operator
def MEASURE_GROUPED_YTD(
    atom_canonical_id: str,
    date_col: str,
    agg: str,
    column: Optional[str],
    group_by_col: Optional[str] = None,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Year-to-date aggregation grouped by a dimension column.

    Applies YTD date scoping (Jan 1 of current year → today) BEFORE
    grouping. Combines the time filter of MEASURE_YTD with the
    group-by logic of MEASURE_GROUPED.

    Args:
        atom_canonical_id: canonical_id of the atom
        date_col:          date column used for YTD scoping
        agg:               aggregation type (SUM, COUNT_DISTINCT, AVG, etc.)
        column:            column to aggregate
        group_by_col:      column name to group by
        filters:           additional filters applied after YTD scope

    Returns:
        {
            oracle_value: dict {group_key: float},
            row_count:    int,
            group_count:  int,
            start_date:   str,
            end_date:     str,
        }
    """
    from compiler.operators._time_helpers import filter_ytd
    rows = load_csv(atom_canonical_id)
    now  = now_utc()

    # Apply YTD date scope first
    scoped   = filter_ytd(rows, date_col)
    # Then apply any additional filters (state filters etc.)
    filtered = apply_filters(scoped, filters)

    # Group and aggregate
    groups: Dict[str, List[Dict]] = {}
    for r in filtered:
        key = r.get(group_by_col)
        if key is None:
            continue
        groups.setdefault(str(key), []).append(r)

    result = {
        group_key: aggregate(group_rows, agg, column)
        for group_key, group_rows in sorted(groups.items())
    }

    return {
        "oracle_value": result,
        "row_count":    len(filtered),
        "group_count":  len(result),
        "start_date":   f"{now.year}-01-01",
        "end_date":     str(now.date()),
    }


# ── MEASURE_ROW_RATIO ────────────────────────────────────────────────────────
# Computes numerator_col / denominator_col per row, returns sorted dict.
# Used for "per entity" ratios where both columns live on the same atom.

@gpl_operator
def MEASURE_ROW_RATIO(
    atom_canonical_id: str,
    numerator_col:     str,
    denominator_col:   str,
    label_col:         Optional[str]  = None,
    filters:           Optional[List[Dict]] = None,
    top_n:             int            = 10,
    descending:        bool           = True,
) -> Dict:
    """
    Per-row ratio: numerator_col / denominator_col for each row.

    Returns the top_n rows sorted by ratio (descending by default),
    keyed by label_col (or row index if label_col is None).

    Args:
        atom_canonical_id: canonical_id of the atom
        numerator_col:     column used as numerator
        denominator_col:   column used as denominator
        label_col:         column to use as the output key (e.g. 'buyer_name')
        filters:           optional row filters applied before ratio
        top_n:             how many rows to return (default 10)
        descending:        sort direction (default True = highest ratio first)

    Returns:
        {
            oracle_value: dict {label: ratio, ...},
            row_count:    int,
        }
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)

    ratios = []
    for i, row in enumerate(filtered):
        try:
            num = float(row.get(numerator_col, 0) or 0)
            den = float(row.get(denominator_col, 0) or 0)
            ratio = round(num / den, 6) if den else 0.0
        except (TypeError, ValueError):
            ratio = 0.0
        label = str(row.get(label_col, i)) if label_col else str(i)
        ratios.append((label, ratio))

    ratios.sort(key=lambda x: x[1], reverse=descending)
    result = {label: ratio for label, ratio in ratios[:top_n]}

    return {
        "oracle_value": result,
        "row_count":    len(filtered),
    }


# ── MEASURE_MULTI ─────────────────────────────────────────────────────────────

@gpl_operator
def MEASURE_MULTI(
    atom_canonical_id: str,
    columns: List[Tuple[str, str]],
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Multi-column aggregation over an atom's rows in a single pass.

    Used for composite goals that require multiple aggregations from the
    same table in one formula — e.g. "show gross, discount, tax, and net
    amounts across all invoices."

    Args:
        atom_canonical_id: canonical_id of the atom
        columns:           list of (agg, column) tuples, e.g.
                           [("SUM", "gross_amount"), ("SUM", "discount_amount")]
        filters:           optional [{field, op, value}] predicates

    Returns:
        {
            oracle_value: dict {column_name: float},  ← one value per column
            row_count:    int,
            formula_line: str,                        ← auto-injected by decorator
        }
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)

    result = {}
    for agg, col in columns:
        result[col] = aggregate(filtered, agg, col)

    return {
        "oracle_value": result,
        "row_count":    len(filtered),
    }


# ── MEASURE_MULTI_GROUPED ────────────────────────────────────────────────────

@gpl_operator
def MEASURE_MULTI_GROUPED(
    atom_canonical_id: str,
    columns: List[Tuple[str, str]],
    group_by_col: str,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Multi-column aggregation grouped by a dimension — single CSV pass.

    Used for composite goals that need both grouping AND multiple aggregations
    — e.g. "show count and freight cost broken down by shipment status."

    Args:
        atom_canonical_id: canonical_id of the atom
        columns:           list of (agg, column) tuples
        group_by_col:      column to group by
        filters:           optional [{field, op, value}] predicates

    Returns:
        {
            oracle_value: dict {group_key: {column_name: float}},
            row_count:    int,
            group_count:  int,
            formula_line: str,
        }
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)

    groups: Dict[str, List[Dict]] = {}
    for r in filtered:
        key = r.get(group_by_col)
        if key is None:
            continue
        groups.setdefault(str(key), []).append(r)

    result = {}
    for group_key, group_rows in sorted(groups.items()):
        result[group_key] = {
            col: aggregate(group_rows, agg, col)
            for agg, col in columns
        }

    return {
        "oracle_value": result,
        "row_count":    len(filtered),
        "group_count":  len(result),
    }

# ── STATISTICAL DISTRIBUTION OPERATORS ───────────────────────────────────────

def _numeric_vals(rows: List[Dict], column: str) -> List[float]:
    """Extract non-null numeric values from a column."""
    vals = []
    for r in rows:
        v = r.get(column)
        if v is not None:
            try:
                vals.append(float(v))
            except (TypeError, ValueError):
                pass
    return vals


@gpl_operator
def MEASURE_STDDEV(
    atom_canonical_id: str,
    column: str,
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """Standard deviation of a numeric column (sample, ddof=1)."""
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    vals     = _numeric_vals(filtered, column)
    value    = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
    return {"oracle_value": value, "row_count": len(filtered)}


