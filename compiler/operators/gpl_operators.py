# ── MEASURE ───────────────────────────────────────────────────────────────────

@gpl_operator
def MEASURE(
    atom_canonical_id: str,
    agg: str,
    column: Optional[str],
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Simple aggregation over an atom's rows. No time window, no dedup.

    Used for:
      - Dimension tables (customers) — no state snapshots, no time needed
      - Record tables with time=all_time and no grouping
      - Max/min goals (Wave 2)

    Args:
        atom_canonical_id: canonical_id of the atom (= CSV filename stem)
        agg:               COUNT_DISTINCT | COUNT | SUM | AVG | MAX | MIN
        column:            column to aggregate; None is valid only for COUNT(*) types
        filters:           optional [{field, op, value}] predicates

    Returns:
        {oracle_value: float, row_count: int, formula_line: str}
        formula_line is auto-generated by @gpl_operator decorator.
    """
    rows     = load_csv(atom_canonical_id)
    filtered = apply_filters(rows, filters)
    value    = aggregate(filtered, agg, column)

    return {
        "oracle_value": value,
        "row_count":    len(filtered),
    }


# ── MEASURE_SNAPSHOT_DEDUPED ──────────────────────────────────────────────────

@gpl_operator
def MEASURE_SNAPSHOT_DEDUPED(
    atom_canonical_id: str,
    dedup_sort_col: str,
    grain_keys: List[str],
    agg: str,
    column: Optional[str],
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Dedup-then-aggregate for state-type atoms.

    State tables record every status change for an entity (e.g. an order
    that moves from Processing → Shipped → Completed appears as 3 rows).
    We always want the CURRENT state — so we dedup to the latest row per
    grain_key BEFORE applying any filter.

    CRITICAL ORDER (from the doc):
      dedup → filter → aggregate
      NOT: filter → dedup (this silently gives wrong counts)

    Example: "How many Completed orders?"
      Wrong (filter first): keep only Completed rows, then dedup
        → may count old Completed snapshots for orders now Cancelled
      Correct (dedup first): keep latest row per order_id, then filter for Completed
        → counts only orders whose CURRENT state is Completed

    Args:
        atom_canonical_id: which atom to read
        dedup_sort_col:    column used to determine "latest" (usually a date/timestamp)
        grain_keys:        columns that uniquely identify one entity (e.g. ["order_id"])
        agg:               aggregation type
        column:            column to aggregate
        filters:           applied AFTER dedup

    Returns:
        {oracle_value, row_count, dedup_count, formula_line}
    """
    rows     = load_csv(atom_canonical_id)
    deduped  = dedup_latest_per_key(rows, dedup_sort_col, grain_keys)
    filtered = apply_filters(deduped, filters)
    value    = aggregate(filtered, agg, column)

    return {
        "oracle_value": value,
        "row_count":    len(filtered),
        "dedup_count":  len(deduped),
    }


# ── MEASURE_SNAPSHOT_DEDUPED_MONTH ───────────────────────────────────────────

@gpl_operator
def MEASURE_SNAPSHOT_DEDUPED_MONTH(
    atom_canonical_id: str,
    date_col: str,
    dedup_sort_col: str,
    grain_keys: List[str],
    agg: str,
    column: Optional[str],
    which_month: str = "this_month",
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Time-scoped dedup-then-aggregate for state-type atoms.

    For state tables with a time window: filter to the month first,
    then dedup to the latest snapshot within that month, then aggregate.

    Order: time_filter → dedup_within_window → state_filter → aggregate

    Example: "Total quantity_on_hand this month"
      1. Keep only rows where snapshot_date is in this month
      2. Dedup to latest snapshot per inventory_id within this month
      3. SUM(quantity_on_hand) on the deduped rows
    """
    rows = load_csv(atom_canonical_id)

    if which_month == "last_month":
        year, month = previous_year_month()
    else:
        year, month = current_year_month()

    scoped   = filter_by_month(rows, date_col, year, month)
    deduped  = dedup_latest_per_key(scoped, dedup_sort_col, grain_keys)
    filtered = apply_filters(deduped, filters)
    value    = aggregate(filtered, agg, column)

    return {
        "oracle_value": value,
        "row_count":    len(filtered),
        "dedup_count":  len(deduped),
        "year":         year,
        "month":        month,
    }


# ── MEASURE_SNAPSHOT_DEDUPED_QUARTER ─────────────────────────────────────────

@gpl_operator
def MEASURE_SNAPSHOT_DEDUPED_QUARTER(
    atom_canonical_id: str,
    date_col: str,
    dedup_sort_col: str,
    grain_keys: List[str],
    agg: str,
    column: Optional[str],
    which: str = "this_quarter",
    filters: Optional[List[Dict]] = None,
) -> Dict:
    """
    Quarter-scoped dedup-then-aggregate for state-type atoms.
    Order: time_filter → dedup_within_window → state_filter → aggregate
    """
    rows = load_csv(atom_canonical_id)

    if which == "this_quarter":
        year, q = current_quarter()
        start, end = quarter_date_range(year, q)
        period_label = f"{year}-Q{q}"
    elif which == "last_quarter":
        year, q = previous_quarter()
        start, end = quarter_date_range(year, q)
        period_label = f"{year}-Q{q}"
    elif which == "this_year":
        year = now_utc().year
        start, end = year_date_range(year)
        period_label = str(year)
        q = None
    elif which == "last_year":
        year = now_utc().year - 1
        start, end = year_date_range(year)
        period_label = str(year)
        q = None
    else:
        raise ValueError(f"MEASURE_SNAPSHOT_DEDUPED_QUARTER: unknown scope '{which}'")

    scoped   = filter_by_range(rows, date_col, start, end)
    deduped  = dedup_latest_per_key(scoped, dedup_sort_col, grain_keys)
    filtered = apply_filters(deduped, filters)
    value    = aggregate(filtered, agg, column)

    result = {
        "oracle_value": value,
        "row_count":    len(filtered),
        "dedup_count":  len(deduped),
        "period":       period_label,
        "year":         year,
    }
    if "q" in dir() and q is not None:
        result["quarter"] = q
    return result


